export function getComparisonById(id: string): TacticalComparison {
  return TACTICAL_COMPARISONS_6V6.find((c) => c.id === id) || TACTICAL_COMPARISONS_6V6[0];
}

export function findDefaultComparisonForPhase(phase: TacticalPhaseId): TacticalComparison {
  return TACTICAL_COMPARISONS_6V6.find((c) => c.phaseHints.includes(phase)) || TACTICAL_COMPARISONS_6V6[0];
}

export function buildComparisonSequence(comp: TacticalComparison, variant: ComparisonVariant): TacticalSequence {
  const side = variant === 'mistake' ? comp.mistake : comp.correct;
  return {
    id: `cmp_${comp.id}_${variant}`,
    title: `${side.badge} — ${comp.title}`,
    subtitle: side.headline,
    size: '6v6',
    offsideEnabled: false,
    frames: side.frames,
  };
}
